 case(volume)
  0:target_gain=0;1:target_gain=28;2:target_gain=57;3:target_gain=85;4:target_gain=114;
  5:target_gain=142;6:target_gain=171;7:target_gain=199;8:target_gain=228;default:target_gain=256;
