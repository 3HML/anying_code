assign fifo_read=phase==0&&ack_sync[2]==sample_req&&primed&&!sleeping&&!music_paused&&!fifo_empty&&!rst;
always @(posedge clk or posedge rst)begin
 if(rst)begin
  ack_sync<=0;phase<=0;primed<=0;emitting<=0;held_sample<=0;music_product<=0;cue_product<=0;mixed<=0;
  product<=0;gain<=0;music_gain<=0;sample_req<=0;sample_word<=0;meter_word<=0;underruns<=0;
  cue_pending<=0;cue_active<=0;cue_address<=0;cue_repeat<=0;
 end else begin
  ack_sync<={ack_sync[1:0],sample_ack};
  if(cue_valid&&!sleeping)cue_pending<=1;
